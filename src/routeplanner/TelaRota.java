    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
try {

    String id = jTextField1.getText();
    String nome = jTextField2.getText();
    String destino = jTextField3.getText();
    String doca = jTextField4.getText();

    java.sql.Connection conn = Conexao.conectar();

    String sql = "INSERT INTO rota (nome, destino, doca) VALUES (?, ?, ?)";

    java.sql.PreparedStatement ps = conn.prepareStatement(sql);

    ps.setString(1, nome);
    ps.setString(2, destino);
    ps.setString(3, doca);

    ps.executeUpdate();

    javax.swing.JOptionPane.showMessageDialog(this, "Rota cadastrada!");

    jTextField1.setText("");
    jTextField2.setText("");
    jTextField3.setText("");
    jTextField4.setText("");

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());

}
    }//GEN-LAST:event_jButton5ActionPerformed

